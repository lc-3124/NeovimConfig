#!/usr/bin/env bash
# ============================================================================
# 锁屏脚本：先确保屏幕点亮，再用固定壁纸配置启动 hyprlock
# 壁纸路径见 hyprlock.conf 的 background.path
# ============================================================================

# 锁屏前先确保屏幕是亮的：防止在熄屏状态下锁屏导致锁屏界面不可见
# （本脚本同时被 META+L 锁屏 和 META+ALT+L 挂起 复用，一处修复覆盖两个入口）
wlopm --on '*' 2>/dev/null
sleep 0.2

exec hyprlock
