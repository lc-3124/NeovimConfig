  output = "eDP-1",       -- 笔记本内置显示器
  mode = "preferred",     -- 使用显示器首选分辨率/刷新率
  position = "auto",      -- 自动排列（默认 auto-right）
  scale = 1,            -- 分数缩放 1.2x（适配高 DPI 屏幕）
})
