-- ============================================================================
-- 显示器布局模块
-- ============================================================================
-- 本机仅 eDP-1（笔记本内置屏），使用首选分辨率、自动位置、1.2 缩放
-- 如有外接显示器，在此添加更多 hl.monitor() 调用
-- ============================================================================

hl.monitor({
  output = "eDP-1",
  mode = "preferred",
  position = "auto",
  scale = 1.10,
  transform = 0
})

