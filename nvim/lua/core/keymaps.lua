-- ============================================================================
-- 快捷键模块（keymaps）
-- 定义全局（非 buffer 级）的常用快捷键。
-- 说明：
--   * <leader> 是 init.lua 中设置的 "\"
--   * <S-j> 表示 Shift+J，其余同理
-- ============================================================================

-- 缩写：vim.keymap.set → map，方便调用
local map = vim.keymap.set

-- ----------------------------------------------------------------------------
-- 光标移动 / 编辑常用键
-- ----------------------------------------------------------------------------
map("n", "<S-j>", "<C-d>", { desc = "向下翻半页" })   -- 普通模式 Shift+J = 半页下翻
map("n", "<S-k>", "<C-u>", { desc = "向上翻半页" })   -- 普通模式 Shift+K = 半页上翻
map("n", "gf", "<C-o>", { desc = "跳回上一个位置（gd 返回）" }) -- gf 覆盖默认跳文件，等价于 Ctrl+o
map("n", "<leader>w", ":w<CR>", { desc = "保存文件" })    -- \w 保存当前文件
map("n", "<leader>q", ":q<CR>", { desc = "关闭窗口" })    -- \q 关闭当前窗口
map("n", "<leader>ya", ":%y+<CR>", { desc = "复制整个文件" }) -- \ya 全选复制到剪贴板

-- ----------------------------------------------------------------------------
-- 行内四分之一跳转（覆盖内置 H/L，函数实现见 core/autocmds.lua）
--   S-L（即 L）：当前行向后（右）跳转行宽的四分之一
--   S-H（即 H）：当前行向前（左）跳转行宽的四分之一
-- ----------------------------------------------------------------------------
map("n", "L", function() _G.jump_quarter(1) end, { desc = "行内向右跳转 1/4 行" })  -- S-L
map("n", "H", function() _G.jump_quarter(-1) end, { desc = "行内向左跳转 1/4 行" }) -- S-H

-- ----------------------------------------------------------------------------
-- 句块跳转（覆盖内置 C-h / C-l 默认行为）
--   C-l = E：向后跳到下一个「大词」（空白分隔的连续字符段）末尾
--   C-h = gE：向前跳到上一个「大词」末尾
-- 例如 hello、~/home/lc3124 都整段直达末尾；光标悬停在块尾
-- ----------------------------------------------------------------------------
map("n", "<C-l>", "E", { desc = "跳到下一个句块末尾" })  -- C-l = 句块向后跳
map("n", "<C-h>", "gE", { desc = "跳到上一个句块末尾" }) -- C-h = 句块向前跳

