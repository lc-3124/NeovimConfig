-- ============================================================================
-- 快捷键模块（keymaps）
-- 定义全局（非 buffer 级）的常用快捷键。
-- 说明：
--   * <leader> 是 init.lua 中设置的 "\"
--   * <S-j> 表示 Shift+J，其余同理
-- ============================================================================

-- 缩写：vim.keymap.set → map，方便调用
local map = vim.keymap.set

-- ----------------------------------------------------------------------------
-- 光标移动 / 编辑常用键
-- ----------------------------------------------------------------------------
map("n", "<S-j>", "<C-d>", { desc = "向下翻半页" })   -- 普通模式 Shift+J = 半页下翻
map("n", "<S-k>", "<C-u>", { desc = "向上翻半页" })   -- 普通模式 Shift+K = 半页上翻
map("n", "<leader>w", ":w<CR>", { desc = "保存文件" })    -- \w 保存当前文件
map("n", "<leader>q", ":q<CR>", { desc = "关闭窗口" })    -- \q 关闭当前窗口
map("n", "<leader>ya", ":%y+<CR>", { desc = "复制整个文件" }) -- \ya 全选复制到剪贴板

-- ----------------------------------------------------------------------------
-- 剪贴板操作
-- ----------------------------------------------------------------------------
-- 可视模式（选中内容后）\y 复制到系统剪贴板（"+ 寄存器 = 系统剪贴板）
map("v", "<leader>y", '"+y', { desc = "复制到系统剪贴板" })

-- ----------------------------------------------------------------------------
-- 缓冲区（buffer）快速跳转
-- 生成 1~9 个 buffer 的跳转快捷键：\b1 ~ \b9
-- buffer 是 Neovim 中"打开的文件"的概念，多个文件就有多个 buffer
-- ----------------------------------------------------------------------------
for i = 1, 9 do
  -- :buffer N 跳到第 N 个缓冲区
  map("n", ("<leader>b%d"):format(i), (":buffer %d<CR>"):format(i), { desc = ("跳转到缓冲区 %d"):format(i) })
end
-- 第 10 个缓冲区用 \b0（因为 0 在键盘上方便）
map("n", "<leader>b0", ":buffer 10<CR>", { desc = "跳转到缓冲区 10" })
